// Precompute the landing globe's land mask.
//
// The globe places dots on an even Fibonacci sphere of DOT_COUNT points and
// keeps the ones on land. Doing that test in the browser meant shipping and
// parsing the Natural Earth land polygons (world-atlas, ISC) on every visit;
// here it runs once and the result is stored as a base64 bitset (~2 KB).
//
//   node scripts/build-globe-dots.mjs
//
// Writes src/components/landing/globeDots.js. Re-run only if DOT_COUNT changes.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { feature } from 'topojson-client'

const DOT_COUNT = 16000
const here = (path) => fileURLToPath(new URL(path, import.meta.url))
const land = JSON.parse(readFileSync(here('../node_modules/world-atlas/land-110m.json'), 'utf8'))

const geo = feature(land, land.objects.land)
const features = geo.type === 'FeatureCollection' ? geo.features : [geo]
const polygons = features.flatMap(({ geometry }) =>
  geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.coordinates,
)

// Bounding boxes skip most polygons for each point.
const boxes = polygons.map((polygon) => {
  let [minX, minY, maxX, maxY] = [Infinity, Infinity, -Infinity, -Infinity]
  for (const [x, y] of polygon[0]) {
    minX = Math.min(minX, x)
    maxX = Math.max(maxX, x)
    minY = Math.min(minY, y)
    maxY = Math.max(maxY, y)
  }
  return { polygon, minX, minY, maxX, maxY }
})

// Even-odd ray casting over every ring, the same rule the old canvas fill used.
function insideRing(ring, x, y) {
  let inside = false
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i]
    const [xj, yj] = ring[j]
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside
  }
  return inside
}

function onLand(lon, lat) {
  for (const box of boxes) {
    if (lon < box.minX || lon > box.maxX || lat < box.minY || lat > box.maxY) continue
    let inside = false
    for (const ring of box.polygon) if (insideRing(ring, lon, lat)) inside = !inside
    if (inside) return true
  }
  return false
}

const golden = Math.PI * (3 - Math.sqrt(5))
const bits = new Uint8Array(Math.ceil(DOT_COUNT / 8))
let landCount = 0
for (let i = 0; i < DOT_COUNT; i++) {
  const y = 1 - (i / (DOT_COUNT - 1)) * 2
  const r = Math.sqrt(1 - y * y)
  const x = Math.cos(golden * i) * r
  const z = Math.sin(golden * i) * r
  const lat = (Math.asin(y) * 180) / Math.PI
  const lon = (Math.atan2(x, z) * 180) / Math.PI
  if (onLand(lon, lat)) {
    bits[i >> 3] |= 1 << (i & 7)
    landCount++
  }
}

const out = `// Generated by scripts/build-globe-dots.mjs from Natural Earth 110m land
// (world-atlas, ISC). Do not edit by hand. Bit i set = Fibonacci-sphere point i
// (of DOT_COUNT) is on land. ${landCount} land dots.
export const DOT_COUNT = ${DOT_COUNT}
export const LAND_MASK = '${Buffer.from(bits).toString('base64')}'
`
writeFileSync(here('../src/components/landing/globeDots.js'), out)
console.log(`globeDots.js: ${landCount} of ${DOT_COUNT} points on land, ${out.length} bytes`)
